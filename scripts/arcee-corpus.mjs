// Writes everything Arcee (the site's chatbot) knows to docs/arcee-corpus.md, straight from the content files.
// Run: npm run arcee:corpus
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = fileURLToPath(new URL("..", import.meta.url));
const jiti = createJiti(import.meta.url, { alias: { "@": `${root}src` } });
const { buildCorpus } = await jiti.import("../src/lib/arcee/corpus.ts");
const { buildInstructions } = await jiti.import("../src/lib/arcee/prompt.ts");

const corpus = buildCorpus();
const words = corpus.reduce((n, c) => n + c.text.split(/\s+/).length, 0);
const lines = [
  "# What Arcee knows",
  "",
  "_Generated by `npm run arcee:corpus` from the site's content files. Don't edit by hand: change the content (src/content/*, src/lib/arcee/corpus.ts) and regenerate._",
  "",
  `${corpus.length} documents, about ${words.toLocaleString()} words. For each question Arcee is sent the two core documents (who Itesh is, the site's pages) plus the ~7 that best match the question and the two turns before it.`,
  "",
  "## The documents",
  "",
  ...corpus.flatMap((c) => [`### ${c.title}`, `\`${c.id}\` · page ${c.url}`, "", c.text, ""]),
  "## Arcee's instructions",
  "",
  "With the documents for a question inserted at the end (here: just the two core ones).",
  "",
  "```text",
  buildInstructions(corpus.filter((c) => c.id === "about-itesh" || c.id === "site-map")),
  "```",
  "",
];
writeFileSync(`${root}docs/arcee-corpus.md`, lines.join("\n"));
console.log(`wrote docs/arcee-corpus.md: ${corpus.length} documents, ~${words} words`);
